"""
Generates COMPACT, search-query-style natural-language rewrites of KEGG
pathway names, for the pathways that passed the objective selection
criteria in pathway_final_choice.py.

This is a second, independently-motivated phrasing condition, alongside the
explanatory-sentence style already generated by pathway_nl_queries.py
(saved to pathway_nl_queries.csv). Rationale: that first prompt asked for a
"description... the way a researcher would type it into a search box," but
what it actually produced was uniform explanatory prose ("How cells build
proteins by assembling amino acids..."). That register matches the LLM
interpretation step in the planned Streamlit tool (Claude explaining
retrieved proteins to a researcher -- CLAUDE.md step 8-9), not the
retrieval QUERY itself (CLAUDE.md step 5-6 -- what a researcher actually
types to search). This prompt targets that query-time register instead:
short, compact, noun-phrase style.

Decided and locked before rerunning AUROC with this style -- same
methodology as the first natural-language experiment (one fixed template,
applied identically, before seeing any results).

Usage:
    uv run python src/evaluation/pathway_nl_queries_compact.py
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import pandas as pd
import anthropic

SELECTION_PATH = Path("data/evaluation/pathway_final_choice.csv")
OUT_PATH = Path("data/evaluation/pathway_nl_queries_compact.csv")

MODEL = "claude-opus-4-8"

PROMPT_TEMPLATE = (
    "Rewrite this KEGG biological pathway name as a short natural-language "
    "search query -- the way a cancer researcher would type it into a "
    "search box to find related proteins. Use a compact descriptive phrase "
    "(3-8 words), NOT a full sentence, NOT a question, and NOT an "
    "explanation of how something works. Do not include any specific gene "
    "or protein names. Respond with only the rewritten query phrase, "
    "nothing else.\n\n"
    "Pathway name: {pathway_name}"
)


def main():
    # --- Load pathways and keep only the objectively-selected 245 ---
    df = pd.read_csv(SELECTION_PATH)
    df = df[df["passes_all_filters"]].reset_index(drop=True)
    print(f"Generating compact search-query rewrites for {len(df)} pathways ...")

    client = anthropic.Anthropic()

    # --- Call the API once per pathway, synchronously, in order ---
    nl_queries = []
    for i, pathway_name in enumerate(df["pathway"]):
        try:
            response = client.messages.create(
                model=MODEL,
                max_tokens=100,
                output_config={"effort": "low"},
                messages=[{
                    "role": "user",
                    "content": PROMPT_TEMPLATE.format(pathway_name=pathway_name),
                }],
            )
            text = next((b.text for b in response.content if b.type == "text"), "")
            nl_queries.append(text.strip())
        except anthropic.APIError as e:
            print(f"  [{i}] {pathway_name!r} failed: {e}")
            nl_queries.append(None)

        if (i + 1) % 25 == 0 or (i + 1) == len(df):
            print(f"  {i + 1}/{len(df)} done")

    # --- Save pathway -> compact query mapping to CSV ---
    df["nl_query_compact"] = nl_queries
    out_df = df[["pathway", "nl_query_compact"]].rename(columns={"pathway": "raw_name"})
    out_df.to_csv(OUT_PATH, index=False)

    print(f"\nSaved {len(out_df)} compact search queries to {OUT_PATH}")
    print(out_df.head(10).to_string(index=False))


if __name__ == "__main__":
    main()
