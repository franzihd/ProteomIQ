"""
Shared GO-OBO parsing utility for the zero-shot text-to-protein retrieval
evaluation (build_go_retrieval_eligible_terms.py / zero_shot_go_retrieval_
eval.py). Parses data/go/go-basic.obo (already cached locally -- see
CLAUDE.md section 11, downloaded once by build_go_mf_eval_set.py) into a
{go_id: {"name": ..., "def": ..., "namespace": ...}} lookup.

Why not goatools.obo_parser.GODag: GODag is already a project dependency
(used for DAG traversal / mapslim() in build_go_mf_eval_set.py) and does
parse "name:" and "namespace:" -- but confirmed directly (empty `defn`
attribute on a loaded GOTerm) that it does NOT parse or expose the "def:"
line at all. Since the official GO natural-language DEFINITION is one of
the two query representations this evaluation needs (the other being the
term name), a small dedicated parser is used instead of half-relying on
GODag for definitions it doesn't have.

GO term names and definitions are official, GO-Consortium-authored text --
read from the same go-basic.obo file already used elsewhere in this
project, not generated by an LLM and not re-fetched from a different
source, so there's exactly one place in the repo that defines what a GO
term "is."

OBO term definition format:
    def: "The molecular actions of ... ." [GOC:xx, PMID:12345]
The quoted text is the definition; the bracketed reference codes are
provenance metadata, not part of the definition text, and are stripped.
"""
import re
from pathlib import Path

GO_OBO_PATH = Path("data/go/go-basic.obo")

DEF_LINE_PATTERN = re.compile(r'^def:\s*"(.*)"\s*\[.*\]\s*$')


def load_go_term_info(obo_path: Path = GO_OBO_PATH) -> dict[str, dict]:
    """Returns {go_id: {"name": str, "def": str, "namespace": str}} for
    every non-obsolete term in the OBO file. "def" is "" if the term has
    no def: line (rare, but not assumed absent -- checked, not assumed)."""
    terms: dict[str, dict] = {}
    current: dict = {}
    in_term = False

    def flush():
        if current.get("id") and not current.get("is_obsolete"):
            terms[current["id"]] = {
                "name": current.get("name", ""),
                "def": current.get("def", ""),
                "namespace": current.get("namespace", ""),
            }

    with open(obo_path, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if line == "[Term]":
                if in_term:
                    flush()
                in_term = True
                current = {}
            elif line == "" and in_term:
                flush()
                in_term = False
                current = {}
            elif in_term:
                if line.startswith("id: "):
                    current["id"] = line[4:]
                elif line.startswith("name: "):
                    current["name"] = line[6:]
                elif line.startswith("namespace: "):
                    current["namespace"] = line[11:]
                elif line.startswith("is_obsolete:"):
                    current["is_obsolete"] = True
                elif line.startswith("def:"):
                    m = DEF_LINE_PATTERN.match(line)
                    current["def"] = m.group(1) if m else ""
        if in_term:
            flush()

    return terms


if __name__ == "__main__":
    # Quick self-check when run directly: confirm names AND defs parse for
    # one term per aspect.
    info = load_go_term_info()
    print(f"Parsed {len(info)} non-obsolete GO terms with name/def/namespace")
    for go_id in ["GO:0003677", "GO:0008150", "GO:0005575"]:
        t = info.get(go_id)
        if t:
            print(f"\n{go_id} ({t['namespace']})")
            print(f"  name: {t['name']}")
            print(f"  def:  {t['def'][:150]}")
